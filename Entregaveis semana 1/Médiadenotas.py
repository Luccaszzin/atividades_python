nota1 = float(input("Digite a primeira nota: ")) #input para o usuario colocar as notas
nota2 = float(input("Digite a segunda nota: "))
nota3 = float(input("Digite a terceira nota: "))

media = (nota1 + nota2+ nota3) / 3 #dividir a nota, com duas casas decimais, para o usuario ver a media

print(f"A média das notas é: {media:.2f}")


